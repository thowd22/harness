//! The deterministic part of dreaming: merge duplicates, drop transient
//! details, prune stale unused notes and rebuild the `MEMORY.md` index.
//!
//! Everything here works on an in-memory [`Notes`] map, so the whole pass
//! can be computed first and written as one commit. Two invariants hold for
//! every pass and are re-checked by [`check_invariants`] before anything is
//! written:
//!
//! - **source links are preserved**: when bullets merge, the survivor
//!   carries the union of their `(src: ...)` run links;
//! - **explicit preferences are preserved**: a bullet stating a preference
//!   ([`is_preference`]) is never pruned, never removed as transient and
//!   only merged with an exact duplicate.

use std::collections::{BTreeMap, BTreeSet};
use std::sync::LazyLock;

use regex::Regex;
use serde::{Deserialize, Serialize};
use time::{Date, Duration, OffsetDateTime};

use crate::drive::note::{Bullet, Line, Note};
use crate::drive::{MEMORY_FILE, NotePath};
use crate::index::UsageSummary;
use crate::tool::guard;

/// Every note of a checkout, by path.
pub type Notes = BTreeMap<NotePath, Note>;

/// Start of the generated index block in `MEMORY.md`.
pub const INDEX_START: &str = "<!-- harness:index (generated by dreaming; edits are replaced) -->";
/// End of the generated index block.
pub const INDEX_END: &str = "<!-- /harness:index -->";
/// Separator between merged source links (sources contain no spaces).
pub const SOURCE_SEPARATOR: char = ',';
/// Word-set similarity at or above which two non-preference bullets of one
/// note are merged.
pub const NEAR_DUPLICATE: f64 = 0.8;

static PREFERENCE_RE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?i)\b(prefer|prefers|preferred|preference|always|never|don't|do not|please|wants?|likes?|dislikes?|rejected|insists?|instead of)\b",
    )
    .expect("valid regex")
});

/// True when `text` states an explicit user preference or rule (these are
/// always kept).
pub fn is_preference(text: &str) -> bool {
    PREFERENCE_RE.is_match(text)
}

/// Lowercased words of `text` without punctuation, `[[links]]` kept.
fn words(text: &str) -> Vec<String> {
    text.to_lowercase()
        .split(|c: char| !(c.is_alphanumeric() || c == '/' || c == '_' || c == '-'))
        .filter(|w| !w.is_empty())
        .map(str::to_owned)
        .collect()
}

/// The comparison key of a bullet: its words joined by single spaces.
pub fn normalize(text: &str) -> String {
    words(text).join(" ")
}

fn similarity(a: &str, b: &str) -> f64 {
    let a: BTreeSet<String> = words(a).into_iter().collect();
    let b: BTreeSet<String> = words(b).into_iter().collect();
    if a.is_empty() || b.is_empty() {
        return 0.0;
    }
    let inter = a.intersection(&b).count() as f64;
    let union = a.union(&b).count() as f64;
    inter / union
}

/// The run links of a bullet (merged sources are comma separated).
pub fn sources(b: &Bullet) -> Vec<String> {
    b.source
        .as_deref()
        .map(|s| {
            s.split(SOURCE_SEPARATOR)
                .filter(|p| !p.is_empty())
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default()
}

/// Adds `other`'s sources (and a later date) to `into`.
fn absorb(into: &mut Bullet, other: &Bullet) {
    let mut all = sources(into);
    for s in sources(other) {
        if !all.contains(&s) {
            all.push(s);
        }
    }
    if !all.is_empty() {
        into.source = Some(all.join(&SOURCE_SEPARATOR.to_string()));
    }
    into.date = match (into.date, other.date) {
        (Some(a), Some(b)) => Some(a.max(b)),
        (a, b) => a.or(b),
    };
}

/// Why a bullet was removed.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RemovalReason {
    /// Merged into another bullet (its sources moved there).
    Merged,
    /// Task state or a session summary (not durable).
    Transient,
    /// In a note nobody used within the grace period.
    Stale,
}

/// One bullet removed by the pass.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Removed {
    /// The note it was in.
    pub note: String,
    /// Bullet text.
    pub text: String,
    /// Why.
    pub reason: RemovalReason,
    /// Where it was merged to (for [`RemovalReason::Merged`]).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub into: Option<String>,
    /// Its source links when it was removed (merged bullets hand theirs to
    /// the survivor).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub sources: Vec<String>,
}

/// What a consolidation pass changed.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct PassReport {
    /// Removed bullets.
    pub removed: Vec<Removed>,
    /// Notes deleted because they became empty.
    pub notes_deleted: Vec<String>,
    /// Whether the `MEMORY.md` index changed.
    pub index_changed: bool,
}

impl PassReport {
    /// Bullets removed for `reason`.
    pub fn count(&self, reason: RemovalReason) -> usize {
        self.removed.iter().filter(|r| r.reason == reason).count()
    }
}

/// Settings of the deterministic pass.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PassOptions {
    /// Notes unused for this long whose bullets are all older are pruned.
    pub grace: Duration,
    /// "Now", for the grace period.
    pub now: OffsetDateTime,
}

fn priority(p: &NotePath) -> u8 {
    // The always-loaded file wins, then tools, then project notes.
    if p.as_str() == MEMORY_FILE {
        0
    } else if p.as_str().starts_with("tools/") {
        1
    } else {
        2
    }
}

/// Merges duplicate bullets: exact (normalized) duplicates anywhere in the
/// drive, and near duplicates within one note when neither is a preference.
pub fn merge_duplicates(notes: &mut Notes, report: &mut PassReport) {
    // Exact duplicates across notes: keep the copy in the highest-priority
    // note (MEMORY.md, then tools/, then projects/), first occurrence.
    let mut order: Vec<NotePath> = notes.keys().cloned().collect();
    order.sort_by(|a, b| priority(a).cmp(&priority(b)).then(a.cmp(b)));
    let mut seen: BTreeMap<String, (NotePath, usize)> = BTreeMap::new();
    for path in &order {
        let lines = std::mem::take(&mut notes.get_mut(path).expect("listed").lines);
        let mut kept = Vec::with_capacity(lines.len());
        for line in lines {
            let Line::Bullet(b) = line else {
                kept.push(line);
                continue;
            };
            let key = normalize(&b.text);
            match seen.get(&key) {
                Some((owner, idx)) => {
                    let (owner, idx) = (owner.clone(), *idx);
                    let target = if &owner == path {
                        match kept.get_mut(idx) {
                            Some(Line::Bullet(t)) => Some(t),
                            _ => None,
                        }
                    } else {
                        match notes.get_mut(&owner).and_then(|n| n.lines.get_mut(idx)) {
                            Some(Line::Bullet(t)) => Some(t),
                            _ => None,
                        }
                    };
                    if let Some(t) = target {
                        absorb(t, &b);
                        report.removed.push(Removed {
                            note: path.to_string(),
                            text: b.text.clone(),
                            reason: RemovalReason::Merged,
                            into: Some(owner.to_string()),
                            sources: sources(&b),
                        });
                        continue;
                    }
                    kept.push(Line::Bullet(b));
                }
                None => {
                    seen.insert(key, (path.clone(), kept.len()));
                    kept.push(Line::Bullet(b));
                }
            }
        }
        notes.get_mut(path).expect("listed").lines = kept;
    }
    // Near duplicates within a note (never preferences).
    for (path, note) in notes.iter_mut() {
        let mut i = 0;
        while i < note.lines.len() {
            let Line::Bullet(a) = &note.lines[i] else {
                i += 1;
                continue;
            };
            if is_preference(&a.text) {
                i += 1;
                continue;
            }
            let a_text = a.text.clone();
            let mut j = i + 1;
            while j < note.lines.len() {
                let dup = match &note.lines[j] {
                    Line::Bullet(b) => {
                        !is_preference(&b.text) && similarity(&a_text, &b.text) >= NEAR_DUPLICATE
                    }
                    Line::Other(_) => false,
                };
                if dup {
                    let Line::Bullet(b) = note.lines.remove(j) else {
                        unreachable!()
                    };
                    // Keep the longer (usually more complete) text.
                    if let Line::Bullet(a) = &mut note.lines[i] {
                        if b.text.len() > a.text.len() {
                            let old = a.text.clone();
                            a.text = b.text.clone();
                            report.removed.push(Removed {
                                note: path.to_string(),
                                text: old,
                                reason: RemovalReason::Merged,
                                into: Some(path.to_string()),
                                sources: Vec::new(),
                            });
                        } else {
                            report.removed.push(Removed {
                                note: path.to_string(),
                                text: b.text.clone(),
                                reason: RemovalReason::Merged,
                                into: Some(path.to_string()),
                                sources: sources(&b),
                            });
                        }
                        absorb(a, &b);
                    }
                } else {
                    j += 1;
                }
            }
            i += 1;
        }
    }
}

/// Removes task state and session summaries (never preferences).
pub fn remove_transient(notes: &mut Notes, report: &mut PassReport) {
    for (path, note) in notes.iter_mut() {
        note.lines.retain(|l| match l {
            Line::Bullet(b) if !is_preference(&b.text) => match guard::check_content(&b.text) {
                Err(r)
                    if matches!(
                        r.kind,
                        guard::RejectKind::TaskState | guard::RejectKind::SessionSummary
                    ) =>
                {
                    report.removed.push(Removed {
                        note: path.to_string(),
                        text: b.text.clone(),
                        reason: RemovalReason::Transient,
                        into: None,
                        sources: sources(b),
                    });
                    false
                }
                _ => true,
            },
            _ => true,
        });
    }
}

/// Prunes notes (other than `MEMORY.md`) that no session read or found
/// within the grace period and whose bullets are all older than it.
/// Preference bullets stay.
pub fn prune_stale(
    notes: &mut Notes,
    usage: &BTreeMap<String, UsageSummary>,
    opts: &PassOptions,
    report: &mut PassReport,
) {
    let cutoff = opts.now - opts.grace;
    let cutoff_date: Date = cutoff.date();
    for (path, note) in notes.iter_mut() {
        if path.as_str() == MEMORY_FILE {
            continue;
        }
        let used = usage
            .get(path.as_str())
            .and_then(|u| u.last_used)
            .is_some_and(|t| t >= cutoff);
        let fresh = note
            .bullets()
            .any(|b| b.date.is_none_or(|d| d >= cutoff_date));
        if used || fresh {
            continue;
        }
        note.lines.retain(|l| match l {
            Line::Bullet(b) if !is_preference(&b.text) => {
                report.removed.push(Removed {
                    note: path.to_string(),
                    text: b.text.clone(),
                    reason: RemovalReason::Stale,
                    into: None,
                    sources: sources(b),
                });
                false
            }
            _ => true,
        });
    }
}

/// Deletes notes (other than `MEMORY.md`) left without bullets and
/// rewrites `[[links]]` to them to the note their bullets moved to.
pub fn drop_empty(notes: &mut Notes, report: &mut PassReport) {
    let empty: Vec<NotePath> = notes
        .iter()
        .filter(|(p, n)| p.as_str() != MEMORY_FILE && n.is_empty())
        .map(|(p, _)| p.clone())
        .collect();
    let mut moved: BTreeMap<String, String> = BTreeMap::new();
    for p in &empty {
        notes.remove(p);
        report.notes_deleted.push(p.to_string());
        if let Some(into) = report
            .removed
            .iter()
            .filter(|r| r.note == p.as_str())
            .find_map(|r| r.into.clone())
            && let Ok(np) = NotePath::parse(&into)
        {
            moved.insert(p.link().to_owned(), np.link().to_owned());
        }
    }
    if moved.is_empty() {
        return;
    }
    for note in notes.values_mut() {
        for l in &mut note.lines {
            if let Line::Bullet(b) = l {
                for (from, to) in &moved {
                    b.text = b.text.replace(&format!("[[{from}]]"), &format!("[[{to}]]"));
                }
            }
        }
    }
}

/// `MEMORY.md` text without the generated index block.
pub fn strip_index(text: &str) -> String {
    match (text.find(INDEX_START), text.find(INDEX_END)) {
        (Some(s), Some(e)) if e > s => {
            let mut out = text[..s].trim_end().to_owned();
            let rest = text[e + INDEX_END.len()..].trim_start_matches('\n');
            if !rest.is_empty() {
                out.push('\n');
                out.push_str(rest);
            }
            if !out.ends_with('\n') {
                out.push('\n');
            }
            out
        }
        _ => text.to_owned(),
    }
}

/// The generated index block: one line per note other than `MEMORY.md`,
/// `- [[link]] Title (N memories)`, sorted by path.
pub fn index_block(notes: &Notes) -> String {
    let mut s = String::new();
    s.push_str(INDEX_START);
    s.push_str("\n## Index\n");
    for (p, n) in notes.iter().filter(|(p, _)| p.as_str() != MEMORY_FILE) {
        let title = n.title().map_or_else(|| p.default_title(), str::to_owned);
        let count = n.bullets().count();
        s.push_str(&format!(
            "[[{}]] {title} ({count} {})\n",
            p.link(),
            if count == 1 { "memory" } else { "memories" }
        ));
    }
    s.push_str(INDEX_END);
    s.push('\n');
    s
}

/// Renders `MEMORY.md` with a fresh index block at the end. Returns the
/// text and whether it differs from `current`.
pub fn render_memory(notes: &Notes, current: &str) -> (String, bool) {
    let body = notes
        .get(&NotePath::parse(MEMORY_FILE).expect("valid"))
        .map(Note::render)
        .unwrap_or_default();
    let mut out = body.trim_end().to_owned();
    if !out.is_empty() {
        out.push_str("\n\n");
    }
    out.push_str(&index_block(notes));
    let changed = out != current;
    (out, changed)
}

/// Every source link and preference in `notes`.
fn inventory(notes: &Notes) -> (BTreeSet<String>, BTreeSet<String>) {
    let mut srcs = BTreeSet::new();
    let mut prefs = BTreeSet::new();
    for n in notes.values() {
        for b in n.bullets() {
            srcs.extend(sources(b));
            if is_preference(&b.text) {
                prefs.insert(normalize(&b.text));
            }
        }
    }
    (srcs, prefs)
}

/// Verifies the invariants between `before` and `after`: every preference
/// survives, and every source link survives unless every bullet carrying
/// it was removed as transient or stale (merged bullets hand their sources
/// to the survivor, so merging never drops one).
pub fn check_invariants(before: &Notes, after: &Notes, report: &PassReport) -> Result<(), String> {
    let (src_before, pref_before) = inventory(before);
    let (src_after, pref_after) = inventory(after);
    if let Some(p) = pref_before.difference(&pref_after).next() {
        return Err(format!("dreaming would drop the preference `{p}`"));
    }
    let dropped: BTreeSet<&String> = report
        .removed
        .iter()
        .filter(|r| r.reason != RemovalReason::Merged)
        .flat_map(|r| &r.sources)
        .collect();
    if let Some(s) = src_before
        .difference(&src_after)
        .find(|s| !dropped.contains(s))
    {
        return Err(format!("dreaming would drop the source link `{s}`"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use time::macros::{date, datetime};

    fn np(p: &str) -> NotePath {
        NotePath::parse(p).unwrap()
    }

    fn notes(items: &[(&str, &str)]) -> Notes {
        items.iter().map(|(p, t)| (np(p), Note::parse(t))).collect()
    }

    const NOW: OffsetDateTime = datetime!(2026-10-22 12:00 UTC);

    fn opts() -> PassOptions {
        PassOptions {
            grace: Duration::days(30),
            now: NOW,
        }
    }

    #[test]
    fn exact_duplicates_merge_across_notes_keeping_all_sources() {
        let mut n = notes(&[
            (
                "MEMORY.md",
                "# Memory\n- Prefer small commits. (src: harness://run/a · 2026-10-01)\n",
            ),
            (
                "projects/app-1/style.md",
                "# Style\n- prefer small commits (src: harness://run/b · 2026-10-05)\n- Use rustfmt defaults. (src: harness://run/c · 2026-10-05)\n",
            ),
        ]);
        let before = n.clone();
        let mut r = PassReport::default();
        merge_duplicates(&mut n, &mut r);
        let mem: Vec<&Bullet> = n[&np("MEMORY.md")].bullets().collect();
        assert_eq!(mem.len(), 1);
        assert_eq!(sources(mem[0]), ["harness://run/a", "harness://run/b"]);
        assert_eq!(mem[0].date, Some(date!(2026 - 10 - 05)));
        assert_eq!(n[&np("projects/app-1/style.md")].bullets().count(), 1);
        assert_eq!(r.count(RemovalReason::Merged), 1);
        check_invariants(&before, &n, &r).unwrap();
        // The merged suffix round-trips through the note format.
        let text = n[&np("MEMORY.md")].render();
        let again = Note::parse(&text);
        assert_eq!(sources(again.bullets().next().unwrap()).len(), 2);
    }

    #[test]
    fn near_duplicates_merge_but_preferences_need_exact_matches() {
        let mut n = notes(&[(
            "tools/cargo.md",
            "# Cargo\n- Run cargo nextest for the integration test suite (src: harness://run/a · 2026-10-01)\n- Run cargo nextest for the full integration test suite (src: harness://run/b · 2026-10-02)\n- The user prefers cargo nextest over cargo test (src: harness://run/c · 2026-10-03)\n- The user prefers cargo nextest over plain cargo test (src: harness://run/d · 2026-10-04)\n",
        )]);
        let before = n.clone();
        let mut r = PassReport::default();
        merge_duplicates(&mut n, &mut r);
        let texts: Vec<String> = n[&np("tools/cargo.md")]
            .bullets()
            .map(|b| b.text.clone())
            .collect();
        assert_eq!(texts.len(), 3, "{texts:?}");
        assert!(texts[0].contains("full integration"));
        check_invariants(&before, &n, &r).unwrap();
    }

    #[test]
    fn transient_bullets_go_but_preferences_stay() {
        let mut n = notes(&[(
            "projects/app-1/work.md",
            "# Work\n- PR #42 is waiting for review (src: harness://run/a · 2026-10-01)\n- Always rebase instead of merging; PR #12 showed why (src: harness://run/b · 2026-10-01)\n",
        )]);
        let before = n.clone();
        let mut r = PassReport::default();
        remove_transient(&mut n, &mut r);
        assert_eq!(r.count(RemovalReason::Transient), 1);
        assert_eq!(n[&np("projects/app-1/work.md")].bullets().count(), 1);
        check_invariants(&before, &n, &r).unwrap();
    }

    #[test]
    fn prunes_only_stale_unused_notes_after_the_grace_period() {
        let mut n = notes(&[
            (
                "MEMORY.md",
                "- Old general note (src: harness://run/m · 2025-01-01)\n",
            ),
            (
                "tools/old.md",
                "# Old\n- Flag --x was needed for v1 (src: harness://run/a · 2026-01-01)\n- Never use sudo here (src: harness://run/b · 2026-01-01)\n",
            ),
            (
                "tools/used.md",
                "# Used\n- Use -j8 builds (src: harness://run/c · 2026-01-01)\n",
            ),
            (
                "tools/new.md",
                "# New\n- Use the new linker flag (src: harness://run/d · 2026-10-20)\n",
            ),
        ]);
        let usage: BTreeMap<String, UsageSummary> = [(
            "tools/used.md".to_owned(),
            UsageSummary {
                reads: 1,
                search_hits: 0,
                last_used: Some(NOW - Duration::days(2)),
                runs: Default::default(),
            },
        )]
        .into();
        let before = n.clone();
        let mut r = PassReport::default();
        prune_stale(&mut n, &usage, &opts(), &mut r);
        assert_eq!(r.count(RemovalReason::Stale), 1);
        assert_eq!(r.removed[0].text, "Flag --x was needed for v1");
        assert_eq!(
            n[&np("tools/old.md")].bullets().count(),
            1,
            "preference kept"
        );
        assert_eq!(n[&np("tools/used.md")].bullets().count(), 1);
        assert_eq!(n[&np("tools/new.md")].bullets().count(), 1);
        assert_eq!(
            n[&np("MEMORY.md")].bullets().count(),
            1,
            "MEMORY.md is never pruned"
        );
        check_invariants(&before, &n, &r).unwrap();
    }

    #[test]
    fn empty_notes_are_deleted_and_links_follow_merges() {
        let mut n = notes(&[
            (
                "tools/a.md",
                "# A\n- Use the fast path (src: harness://run/a · 2026-10-01)\n",
            ),
            (
                "tools/b.md",
                "# B\n- use the fast path (src: harness://run/b · 2026-10-01)\n",
            ),
            (
                "tools/c.md",
                "# C\n- See [[tools/b]] for speed (src: harness://run/c · 2026-10-01)\n",
            ),
        ]);
        let mut r = PassReport::default();
        merge_duplicates(&mut n, &mut r);
        drop_empty(&mut n, &mut r);
        assert_eq!(r.notes_deleted, ["tools/b.md"]);
        assert!(!n.contains_key(&np("tools/b.md")));
        let c = n[&np("tools/c.md")].bullets().next().unwrap().text.clone();
        assert_eq!(c, "See [[tools/a]] for speed");
    }

    #[test]
    fn index_block_is_regenerated_and_stripped() {
        let n = notes(&[
            (
                "MEMORY.md",
                "# Memory\n- Prefer short answers (src: harness://run/a · 2026-10-01)\n",
            ),
            (
                "tools/cargo.md",
                "# Cargo\n- Use nextest (src: harness://run/b · 2026-10-01)\n",
            ),
        ]);
        let (text, changed) = render_memory(&n, "");
        assert!(changed);
        assert!(text.contains("[[tools/cargo]] Cargo (1 memory)"));
        assert!(text.starts_with("# Memory\n- Prefer short answers"));
        // Index lines are not bullets, so they never become memories.
        assert_eq!(Note::parse(&text).bullets().count(), 1);
        let stripped = strip_index(&text);
        assert_eq!(
            stripped,
            "# Memory\n- Prefer short answers (src: harness://run/a · 2026-10-01)\n"
        );
        assert!(!render_memory(&n, &text).1, "stable when nothing changed");
    }

    #[test]
    fn invariant_check_catches_dropped_preferences_and_sources() {
        let before = notes(&[(
            "tools/x.md",
            "# X\n- Always use tabs (src: harness://run/a · 2026-10-01)\n",
        )]);
        let after = notes(&[("tools/x.md", "# X\n")]);
        assert!(check_invariants(&before, &after, &PassReport::default()).is_err());
        let before = notes(&[(
            "tools/x.md",
            "# X\n- Use -j8 (src: harness://run/a · 2026-10-01)\n",
        )]);
        let after = notes(&[("tools/x.md", "# X\n- Use -j8\n")]);
        assert!(
            check_invariants(&before, &after, &PassReport::default())
                .unwrap_err()
                .contains("source link")
        );
    }
}
